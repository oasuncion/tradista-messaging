/**
 * Base mapped superclass for Tradista Messaging JPA entities.
 * 
 * @author Olivier Asuncion
 */
@MappedSuperclass
public abstract class BaseMessagingEntity implements Serializable {

	private static final long serialVersionUID = 1L;

	@Id
	@GeneratedValue(strategy = GenerationType.AUTO)
	private Long id;

	public Long getId() {
		return id;
	}

	public void setId(Long id) {
		this.id = id;
	}

	@Override
	public int hashCode() {
		return Objects.hash(id);
	}

	@Override
	public boolean equals(Object obj) {
		if (this == obj)
			return true;
		if (obj == null)
			return false;
		if (getClass() != obj.getClass())
			return false;
		BaseMessagingEntity other = (BaseMessagingEntity) obj;
		if (id == null || other.id == null) {
			return false;
		}
		return Objects.equals(id, other.id);
	}
}
