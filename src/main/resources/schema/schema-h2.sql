CREATE TABLE IF NOT EXISTS MESSAGING_QUEUE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(255),
    CAPACITY INTEGER
);

CREATE TABLE IF NOT EXISTS MESSAGING_FILTER_CONFIG (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    FILTER_CLASS VARCHAR(255) NOT NULL,
    DESCRIPTION VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS MESSAGING_ROUTER (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(255),
    DEFAULT_OUTPUT_QUEUE_ID BIGINT,
    CONSTRAINT FK_ROUTER_DEFAULT_QUEUE FOREIGN KEY (DEFAULT_OUTPUT_QUEUE_ID) REFERENCES MESSAGING_QUEUE(ID)
);

CREATE TABLE IF NOT EXISTS MESSAGING_ROUTING_RULE (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROUTER_ID BIGINT NOT NULL,
    EVENT_TYPE VARCHAR(100) NOT NULL,
    DESTINATION_QUEUE_ID BIGINT NOT NULL,
    CONSTRAINT FK_RULE_ROUTER FOREIGN KEY (ROUTER_ID) REFERENCES MESSAGING_ROUTER(ID) ON DELETE CASCADE,
    CONSTRAINT FK_RULE_DEST_QUEUE FOREIGN KEY (DESTINATION_QUEUE_ID) REFERENCES MESSAGING_QUEUE(ID)
);

CREATE TABLE IF NOT EXISTS MESSAGING_ENDPOINT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(255),
    QUEUE_ID BIGINT NOT NULL,
    FILTER_CONFIG_ID BIGINT,
    CONSUMER_CLASS VARCHAR(255),
    STATUS VARCHAR(20) NOT NULL,
    POLLER_DELAY_MS BIGINT,
    POLLER_MAX_MESSAGES INTEGER,
    CONSTRAINT FK_ENDPOINT_QUEUE FOREIGN KEY (QUEUE_ID) REFERENCES MESSAGING_QUEUE(ID),
    CONSTRAINT FK_ENDPOINT_FILTER FOREIGN KEY (FILTER_CONFIG_ID) REFERENCES MESSAGING_FILTER_CONFIG(ID)
);
